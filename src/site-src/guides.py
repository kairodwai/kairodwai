def pages():
    return {'Docs@' + d['slug']: (d.get('path') or '/guide/' + d['slug'] + '/', d['title'], d['desc']) for d in G}


def _body(d):
    b = d['body']()
    if '{RECENT}' in b:
        import portfolio
        b = b.replace('{RECENT}', portfolio.grid(portfolio.CARS[:3], 'h3'))
    return b


def transform(body, slug):
    d = BY[slug]
    def rep(a, b):
        nonlocal body
        assert body.count(a) == 1, (slug, a[:60], body.count(a)); body = body.replace(a, b)
    rep('aria-current="page" style="color: #141414;">เอกสารที่ต้องใช้ขายรถ</span>', 'aria-current="page" style="color: #141414;">' + d['crumb'] + '</span>')
    h0 = body.index('<h1'); h1 = body.index('</h1>', h0) + 5
    end = body.index('</ul>\n</div></section>', h1)
    head = body[h0:body.index('>', h0) + 1]
    body = body[:h0] + head + d['h1'] + '</h1>' + (META.format(pub=th_date(d['pub']), mod=th_date(d['mod'])) if d.get('article', True) else '') + P.format(d['lead']) + _body(d) + body[end + len('</ul>'):]
    rep('color: #0B1A10;">เอกสารพร้อมแล้ว</h2>', 'color: #0B1A10;">' + d.get('band', 'พร้อมขายรถแล้ว') + '</h2>')
    i = body.index('คำถามเรื่องเอกสาร'); a = body.rfind('<section', 0, i); b = body.index('</section>', i) + len('</section>')
    return body[:a] + body[b:]


